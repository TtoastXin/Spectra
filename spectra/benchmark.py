"""Benchmark registry: the six posterior tasks.

Everything here is metadata plus pure-JAX helpers.  Simulators that only exist
in torch/pyro (Two Moons, Gaussian Linear) are not reimplemented; training
data for those is produced by a separate torch-only script and read back as
``.npz``, the same split the ratio fitter uses (torch and JAX cannot
share one process on this cluster).

Coordinates
-----------
Upstream trains with ``z_score_data: false``, so the model's parameter
coordinates are the task coordinates in which the prior JSONs are written:

  * ``gaussian_linear`` / ``gaussian_linear_high``: sbibm raw coordinates,
    training prior ``N(0, 0.1 I)``;
  * ``two_moons``: sbibm raw coordinates, training prior ``U([-1, 1]^2)``;
  * ``oup``: upstream's rescaled coordinates (``U([-1,1]^2)``), the simulator
    applies ``theta_shift/theta_rescale`` itself;
  * ``bav``: standardized coordinates, training prior ``N(0, I)``.

Upstream PriorGuide also ships a Turin task.  It is not part of this release
(no priors, observations or checkpoints for it are included), so it is not
registered here and the scripts reject ``--task turin``.

Every exact-transport formula in :mod:`spectra.transport` is evaluated directly
in these coordinates, without an extra transform.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Optional, Sequence

import jax.numpy as jnp
import numpy as np

UPSTREAM_ENV = "PRIORGUIDE_UPSTREAM"

# Upstream's ``observation_seeds`` list in experiments/posterior/run_prior_guide_*.py.
# This is the runner list; it differs from ``TwoMoons.observation_seeds``
# inside sbibm_task.py, and the shipped observation JSONs follow the runner list.
OBSERVATION_SEEDS = (
    1000000, 1000001, 1000002, 1000003, 1000004,
    1000005, 1000010, 1000012, 1000008, 1000009,
)

PRIOR_TYPES = ("mild", "strong", "mixture")


@dataclass(frozen=True)
class TaskSpec:
    """Static description of one upstream benchmark task."""

    name: str
    theta_dim: int
    x_dim: int
    train_prior_kind: str  # "gaussian" | "uniform"
    exact_branch: str  # "TQ" | "E2": which exact-transport form mild/strong use
    reference: str  # how the reference posterior is produced

    @property
    def num_nodes(self) -> int:
        return self.theta_dim + self.x_dim

    @property
    def node_id(self) -> jnp.ndarray:
        return jnp.arange(self.num_nodes)

    @property
    def posterior_condition_mask(self) -> jnp.ndarray:
        """Upstream's default mask: theta free, x conditioned."""
        return jnp.array(
            [False] * self.theta_dim + [True] * self.x_dim, dtype=jnp.bool_
        )


TASKS = {
    "gaussian_linear": TaskSpec(
        "gaussian_linear", 10, 10, "gaussian", "TQ", "analytic"),
    "gaussian_linear_high": TaskSpec(
        "gaussian_linear_high", 20, 20, "gaussian", "TQ", "analytic"),
    "two_moons": TaskSpec(
        "two_moons", 2, 2, "uniform", "E2", "rejection"),
    "oup": TaskSpec(
        "oup", 2, 25, "uniform", "E2", "npe"),
    "bav": TaskSpec(
        "bav", 5, 98, "gaussian", "TQ", "vbmc"),
    # SLCP is not part of upstream: ``priorg.sim.tasks.task.get_task``
    # routes it to ``SBIBMTask``, whose constructor accepts only two_moons and
    # the two Gaussian Linears, and no slcp priors/observations exist under
    # ``experiments/data``.  It is defined natively in
    # :mod:`spectra.slcp` and its prior/observation JSONs are generated by
    # ``scripts/prepare_slcp.py`` into this repository's ``data/``.
    "slcp": TaskSpec(
        "slcp", 5, 8, "uniform", "E2", "smc"),
}

DATA_DIR = Path(__file__).resolve().parents[1] / "data"


def data_root(task: str, root: Optional[str | os.PathLike] = None,
              rel: Optional[str] = None) -> Path:
    """Root of ``priors/`` and ``observations/`` for one task.

    Every task reads from the repository's ``data/`` directory unless ``root``
    names another directory with the same layout; see ``data/README.md`` for
    where each file comes from.
    """
    return DATA_DIR if root is None else Path(root).expanduser().resolve()


def get_task(name: str) -> TaskSpec:
    try:
        return TASKS[name]
    except KeyError:
        raise ValueError(f"unknown task {name!r}; known: {sorted(TASKS)}") from None


# ------------------------------------------------------------ upstream data --


def upstream_root(root: Optional[str | os.PathLike] = None) -> Path:
    """Resolve the read-only upstream checkout from ``root`` or the environment."""
    raw = root if root is not None else os.environ.get(UPSTREAM_ENV)
    if raw is None:
        raise RuntimeError(f"set ${UPSTREAM_ENV} (or pass --upstream) to the checkout")
    path = Path(raw).expanduser().resolve()
    if not (path / "experiments" / "data" / "priors").is_dir():
        raise RuntimeError(f"{path} does not look like a prior-guide checkout")
    return path


def prior_path(task: str, prior_type: str, prior_id: Optional[int] = None,
               root=None) -> Path:
    name = "training.json" if prior_type == "training" else f"{prior_type}_{prior_id}.json"
    base = data_root(task, root, rel=f"priors/{task}/{name}") / "priors" / task
    if prior_type == "training":
        return base / "training.json"
    return base / f"{prior_type}_{prior_id}.json"


def observation_path(task: str, prior_type: str, prior_id: int, obs_seed: int,
                     root=None) -> Path:
    rel = f"observations/{task}/{prior_type}_{prior_id}/obs_{obs_seed}.json"
    return data_root(task, root, rel=rel) / "observations" / task / \
        f"{prior_type}_{prior_id}" / f"obs_{obs_seed}.json"


def load_prior_json(task: str, prior_type: str, prior_id: Optional[int] = None,
                    root=None) -> dict:
    with open(prior_path(task, prior_type, prior_id, root)) as fh:
        return json.load(fh)


def load_observation(task: str, prior_type: str, prior_id: int, obs_seed: int,
                     root=None) -> tuple[jnp.ndarray, jnp.ndarray]:
    """Return ``(theta_true, x_o)`` for one shipped observation."""
    with open(observation_path(task, prior_type, prior_id, obs_seed, root)) as fh:
        obs = json.load(fh)
    return jnp.atleast_1d(jnp.array(obs["theta"])), jnp.atleast_1d(jnp.array(obs["x"]))


def prior_json_hash(task: str, prior_type: str, prior_id: Optional[int] = None,
                    root=None) -> str:
    import hashlib

    return hashlib.sha256(
        prior_path(task, prior_type, prior_id, root).read_bytes()
    ).hexdigest()[:16]


# --------------------------------------------------------- training support --


def training_support(task: str, root=None) -> Optional[tuple[np.ndarray, np.ndarray]]:
    """``(low, high)`` of the uniform training box, or ``None`` for Gaussian priors.

    Needed for the support caveat: a frozen base posterior cannot place
    clean mass outside ``supp(pi_train)``, so for the uniform-training tasks the
    fraction of target mass outside this box is an irreducible coverage floor.
    """
    js = load_prior_json(task, "training", root=root)
    if js["dist"] != "uniform":
        return None
    return np.asarray(js["low"], float), np.asarray(js["high"], float)


# ------------------------------------------------------- reusable artifacts --


def source_hashes(paths) -> dict:
    """Truncated content hash of each source file a run depended on.

    A git commit plus a list of dirty filenames does not identify the code that
    ran when the tree has uncommitted changes.
    """
    import hashlib
    from pathlib import Path

    out = {}
    for path in paths:
        path = Path(path)
        if path.is_file():
            out[path.name] = hashlib.sha256(path.read_bytes()).hexdigest()[:16]
    return out


def outside_box_fraction(samples: np.ndarray, box) -> float:
    """Fraction of ``samples`` (n, d) falling outside the closed box ``(low, high)``."""
    low, high = box
    inside = np.all((samples >= low) & (samples <= high), axis=-1)
    return float(1.0 - inside.mean())
